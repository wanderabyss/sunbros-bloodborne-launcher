"""Writes the game's and the launcher's copies of a setting's choices from one table.

scripts/dlss_models.tsv -> gpu/shim/bbport_dlss_models.h and launcher/bbport_dlss_models.py.
Both outputs are committed, so the build needs no Python; tests/test_settings_tables.py fails
when they no longer match the table. --check exits 1 instead of writing."""
import argparse
from pathlib import Path
import sys

PORT = Path(__file__).resolve().parents[1]
TABLE = PORT / 'scripts' / 'dlss_models.tsv'
HEADER = PORT / 'gpu' / 'shim' / 'bbport_dlss_models.h'
MODULE = PORT / 'launcher' / 'bbport_dlss_models.py'
NOTE = 'Generated by scripts/gen_settings_tables.py from scripts/dlss_models.tsv: edit the table, not this file.'


def read_table(path=TABLE):
    """(rows in menu order as dicts, {directive: text})."""
    rows, directives, columns = [], {}, None
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        fields = line.split('\t')
        if line.startswith('@'):
            directives[fields[0][1:]] = fields[1]
        elif columns is None:
            columns = fields
        else:
            if len(fields) != len(columns):
                raise ValueError(f'{path.name}: {len(fields)} fields for {len(columns)} columns: {line!r}')
            row = dict(zip(columns, fields))
            row['index'], row['preset'] = int(row['index']), int(row['preset'])
            rows.append(row)
    indices = sorted(row['index'] for row in rows)
    if indices != list(range(len(rows))):
        raise ValueError(f'{path.name}: indices {indices} are not 0..{len(rows) - 1}')
    for key in ('id', 'ini'):
        names = [row[key].lower() for row in rows]
        if len(set(names)) != len(names):
            raise ValueError(f'{path.name}: duplicate {key}')
    return rows, directives


def c_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def header(rows, directives):
    by_index = sorted(rows, key=lambda row: row['index'])
    enum = ', '.join(f"DlssModel{row['id']} = {row['index']}" for row in by_index)
    names = ', '.join(c_string(row['ini']) for row in by_index)
    presets = ', '.join(str(row['preset']) for row in by_index)
    labels = ''.join(f"\n    {c_string(row['name'] + ' - ' + row['summary'])}," for row in by_index)
    order = ', '.join(f"DlssModel{row['id']}" for row in rows)
    cases = ''.join(f"\n    case {row['preset']}: return {c_string(row['id'] + ' (' + row['family'] + ')')};"
                    for row in sorted(rows, key=lambda row: row['preset']) if row['preset'])
    return f'''// SPDX-License-Identifier: GPL-2.0-or-later
// {NOTE}
// BbDlssPresetName is plain C (bbport_nvidia_gpu.h, tools/); the rest is the game's C++.
#pragma once

/// The model a DLSS render preset is ("K (DLSS 4)"), for the log and the menu; "the driver's
/// choice" for 0 or a preset not offered.
static inline const char* BbDlssPresetName(unsigned preset) {{
    switch (preset) {{{cases}
    default: return "the driver's choice";
    }}
}}

#ifdef __cplusplus
namespace BbSettings {{

/// DLSS model (bbport.ini dlss_model, the bridge's NVSDK_NGX_DLSS_Hint_Render_Preset); the values
/// are saved in settings, so a model keeps its index.
enum DlssModel : int {{ {enum}, DlssModelCount }};
/// bbport.ini dlss_model= of each model (matched without case).
inline constexpr const char* DlssModelIniNames[DlssModelCount] = {{{names}}};
/// The NGX preset of each model; Auto's is chosen per frame (BbDlssAutoPreset).
inline constexpr unsigned DlssModelPresets[DlssModelCount] = {{{presets}}};
/// The in-game menu's label of each model.
inline constexpr const char* DlssModelLabels[DlssModelCount] = {{{labels}
}};
/// The order the menus list the models in.
inline constexpr int DlssModelMenuOrder[DlssModelCount] = {{{order}}};
/// What the setting does, for the menu's hint (a string literal, to append to).
#define BB_DLSS_MODEL_HELP {c_string(directives['help'])}

}} // namespace BbSettings
#endif
'''


def module(rows, directives):
    choices = ''.join(f"\n    ({row['ini']!r}, ({row['name'] + ': ' + row['summary']!r}, "
                      f"{row['name_ru'] + ': ' + row['summary_ru']!r})),"
                      for row in rows)
    return f'''# SPDX-License-Identifier: GPL-2.0-or-later
# {NOTE}
"""The DLSS model choices (bbport.ini dlss_model) in menu order, as (value, (English, Russian))."""

DLSS_MODELS = [{choices}
]
DLSS_MODEL_HELP = {directives['help']!r}
'''


def outputs():
    rows, directives = read_table()
    return {HEADER: header(rows, directives), MODULE: module(rows, directives)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 when an output is out of date')
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding='utf-8').replace('\r\n', '\n') if path.is_file() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_bytes(text.encode('utf-8'))
            print(f'wrote {path.relative_to(PORT)}')
    if args.check and stale:
        print('out of date: ' + ', '.join(str(p.relative_to(PORT)) for p in stale) +
              ' (run python bloodborne_pc/scripts/gen_settings_tables.py)', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
